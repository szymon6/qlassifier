// Generates lib/api-types.gen.ts from the API contract (TDD §6.7, ADR 0007).
//   node scripts/gen-types.mjs          write the file
//   node scripts/gen-types.mjs --check  exit 1 when the committed file differs from the schemas
// Source: src/qlassifier/schemas/api.json (every contract model once under $defs),
// written by scripts/gen_schemas.py from the pydantic models.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const SCHEMA = resolve(here, "../../src/qlassifier/schemas/api.json");
const OUT = resolve(here, "../lib/api-types.gen.ts");

const BANNER = `/* Generated by frontend/scripts/gen-types.mjs from src/qlassifier/schemas/api.json.
 * Do not edit: run \`npm run gen:types\` after \`python scripts/gen_schemas.py\`. */`;

export async function generate() {
  const schema = JSON.parse(await readFile(SCHEMA, "utf8"));
  // The bundle root has no properties of its own: expose the $defs only.
  const root = { ...schema, type: "object", properties: {}, additionalProperties: false };
  return compile(root, "QlassifierApiV1", {
    bannerComment: BANNER,
    unreachableDefinitions: true,
    additionalProperties: false,
    strictIndexSignatures: false,
    enableConstEnums: false,
    format: true,
    style: { printWidth: 100, semi: true, singleQuote: false, trailingComma: "all" },
  });
}

const check = process.argv.includes("--check");
const text = await generate();
if (check) {
  let current = "";
  try {
    current = await readFile(OUT, "utf8");
  } catch {
    // Missing file counts as out of date.
  }
  if (current !== text) {
    console.error("lib/api-types.gen.ts is out of date with src/qlassifier/schemas/api.json.");
    console.error("Fix: cd frontend && npm run gen:types");
    process.exit(1);
  }
  console.log("api-types.gen.ts in sync with the schemas.");
} else {
  await writeFile(OUT, text);
  console.log(`wrote ${OUT}`);
}
