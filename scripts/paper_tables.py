@dataclass(frozen=True)
class Look:
    """One phase-7 run of the BT-6 question on protein data: geometry mode vs the best classical model."""

    exp: str
    label: str
    paired: Paired
    geo_ba: float
    best_ba: float
    seeds: tuple[int, int]


def history(experiments: Path) -> tuple[list[Look], dict[str, Paired]]:
    """Phase-7 BT-6 history (protein) and the ``deep_quakes`` loss, recomputed from the raw per-seed files."""
    out = []
    specs = (
        ("e07", "protein_strands, residue-level split", "e07-structure-fit/protein.csv", "protein_strands", 0.95),
        ("e11", "protein_strands, chain-grouped", "e11-grouped-split/results.csv", "protein_strands", 0.95),
        ("e12", "protein_div6, chain-grouped", "e12-diverse-chains/div6.csv", "protein_div6", 0.975),
        ("e12", "protein_div10, chain-grouped", "e12-diverse-chains/div10.csv", "protein_div10", 0.975),
    )
    for exp, label, rel, ds, level in specs:
        rows = phase7_rows(experiments, rel, ds)
        best = phase7_best_classical(rows)
        seeds = [int(r["seed"]) for r in rows]
        paired = phase7_paired(rows, "qlass_geo", best, level)
        out.append(
            Look(exp, label, paired, phase7_mean(rows, "qlass_geo"), phase7_mean(rows, best), (min(seeds), max(seeds)))
        )
    quakes = phase7_rows(experiments, "e07-structure-fit/quakes.csv", "deep_quakes")
    wide = phase7_rows(experiments, "e09-quake-grid/results.csv", "deep_quakes")
    loss = {
        "quakes": phase7_paired(quakes, "qlass_geo", phase7_best_classical(quakes)),
        "quakes.wide": phase7_paired([*wide, *[r for r in quakes if r["model"] == "random_forest"]],
                                     "qlass_geo_wide", "random_forest"),
        "quakes.rbf": phase7_paired(quakes, "qlass_geo", "rbf_svm"),
    }  # fmt: skip
    return out, loss


