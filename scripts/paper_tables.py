@dataclass
class Values:
    """Named numbers for the prose: ``\\val{key}`` in ``main.tex``."""

    items: dict[str, str] = field(default_factory=dict)

    def add(self, key: str, text: str) -> None:
        """Register one value; keys are unique."""
        if key in self.items:
            raise ValueError(f"duplicate value key {key}")
        if not re.fullmatch(r"[a-z0-9.]+", key):
            raise ValueError(f"bad value key {key!r}")
        self.items[key] = text

    def render(self) -> str:
        """``values.tex``."""
        lines = [HEADER.rstrip("\n"), r"% Usage in main.tex: \val{key}."]
        lines += [rf"\qlvalue{{{k}}}{{{v}}}" for k, v in self.items.items()]
        return "\n".join(lines) + "\n"


def model(r: Mapping[str, Any], model_id: str) -> dict[str, Any] | None:
    """The leaderboard row of a model, or None."""
    return next((m for m in r["models"] if m["id"] == model_id), None)


def metric(r: Mapping[str, Any], model_id: str, name: str = "balanced_accuracy") -> dict[str, Any]:
    """A model's metric summary (mean, std, CI, tie flag)."""
    m = model(r, model_id)
    if m is None:
        raise InputError(f"{r['dataset']['id']}: no model {model_id}")
    s: dict[str, Any] = m["metrics"][name]
    return s


def comparison(r: Mapping[str, Any], model_id: str, name: str = "balanced_accuracy") -> dict[str, Any]:
    """Qlassifier - model, paired over seeds."""
    for c in r["comparisons"]:
        if c["model"] == model_id:
            s: dict[str, Any] = c["metrics"][name]
            return s
    raise InputError(f"{r['dataset']['id']}: no comparison with {model_id}")


def model_name(r: Mapping[str, Any], model_id: str) -> str:
    """Display name of a model, as the benchmark wrote it."""
    m = model(r, model_id)
    if m is None:
        raise InputError(f"{r['dataset']['id']}: no model {model_id}")
    return str(m["name"])


def noise_summary(r: Mapping[str, Any]) -> dict[tuple[str, str, str], dict[str, Any]]:
    """Noise summary rows by (part, model, device)."""
