def sweep_curve(cells: Sequence[Mapping[str, str]], part: str, model_id: str) -> dict[float, list[float]]:
    """Accuracies per noise scale for one model in one part of the sweep."""
    out: dict[float, list[float]] = {}
    for r in cells:
        if r["part"] == part and r["model"] == model_id:
            out.setdefault(float(r["scale"]), []).append(float(r["accuracy"]))
    if not out:
        raise InputError(f"noise sweep has no part {part} rows for {model_id}")
    return out


def sweep_auc(curve: Mapping[float, Sequence[float]]) -> float:
    """Mean accuracy over the swept scale range (trapezoid rule, normalised by the span)."""
    scales = sorted(curve)
    means = [fmean(curve[s]) for s in scales]
    span = scales[-1] - scales[0]
    return sum((scales[i + 1] - scales[i]) * (means[i] + means[i + 1]) / 2 for i in range(len(scales) - 1)) / span


def sweep_values(v: Values, cells: Sequence[Mapping[str, str]]) -> None:
    """``sweep.*``: the FakeFez error rates scaled 0x-3x (e02), Breast Cancer."""

    def drops(part: str, model_id: str, scale: float) -> list[float]:
        xs = [
            float(r["drop_pp"])
            for r in cells
            if r["part"] == part and r["model"] == model_id and float(r["scale"]) == scale
        ]
        if not xs:
            raise InputError(f"noise sweep has no part {part} {model_id} cells at scale {scale}")
        return xs

    def r_at(part: str, model_id: str, scale: float) -> float:
        xs = [
            float(r["kernel_r"])
            for r in cells
            if r["part"] == part and r["model"] == model_id and float(r["scale"]) == scale
        ]
        return fmean(xs)

    scales = sorted({float(r["scale"]) for r in cells if r["part"] == "A"})
    v.add("sweep.scales", ", ".join(f"{s:g}" for s in scales))
    v.add("sweep.max", f"{max(scales):g}")
    v.add("sweep.a.seeds", str(len({r["seed"] for r in cells if r["part"] == "A"})))
    v.add("sweep.b.seeds", str(len({r["seed"] for r in cells if r["part"] == "B" and r["model"] == "qlassifier"})))
    v.add("sweep.zz.seeds", str(len({r["seed"] for r in cells if r["part"] == "B" and r["model"] == "zz_qsvc"})))
    v.add("sweep.q.drop1", signed(fmean(drops("A", "qlassifier", 1.0)), 2))
    v.add("sweep.q.drop1.worst", fixed(max(drops("A", "qlassifier", 1.0)), 2))
    v.add("sweep.q.drop3", signed(fmean(drops("A", "qlassifier", max(scales))), 2))
    v.add("sweep.q.r3", fixed(r_at("A", "qlassifier", max(scales))))
    v.add("sweep.fqk.drop0", fixed(fmean(drops("B", "fqk_bandwidth_linear", 0.0)), 1))
    v.add("sweep.fqk.drop3", fixed(fmean(drops("B", "fqk_bandwidth_linear", max(scales))), 1))
    v.add("sweep.fqk.r3", fixed(r_at("B", "fqk_bandwidth_linear", max(scales)), 2))
    v.add("sweep.zz.r0", fixed(r_at("B", "zz_qsvc", 0.0), 2))
    v.add("sweep.zz.r3", fixed(r_at("B", "zz_qsvc", max(scales)), 2))
    for model_id, key in (("qlassifier", "q"), ("fqk_bandwidth_linear", "fqk"), ("zz_qsvc", "zz")):
        v.add(f"sweep.auc.{key}", fixed(sweep_auc(sweep_curve(cells, "B", model_id))))


