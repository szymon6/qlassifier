def hardware_runs(stage2: Path) -> list[dict[str, Any]]:
    """Every ``run-seed*/record.json`` of e07 with its FakeFez prediction (``prediction.json``) and verdict."""
    folder = stage2 / "e07-hardware-point"
    preds = read_json(folder / "prediction.json")["seeds"]
    runs = []
    for path in sorted(folder.glob("run-seed*/record.json"), key=lambda p: int(p.parent.name.removeprefix("run-seed"))):
        rec = read_json(path)
        pred = preds.get(str(rec["seed"]))
        if pred is None:
            raise InputError(f"no prediction for hardware seed {rec['seed']} (run the e07 dry run)")
        p = pred["fake_fez"]["variant1_inference_accuracy"]
        acc = rec["analysis"]["variant1_inference"]["accuracy"]
        rec["prediction"] = p
        rec["delta_pp"] = 100 * (acc - p["mean"])
        rec["pass_2pp"] = abs(rec["delta_pp"]) <= 2.0 + 1e-9
        rec["in_range"] = p["min"] - 1e-9 <= acc <= p["max"] + 1e-9
        runs.append(rec)
    if not runs:
        raise InputError("no hardware runs under e07-hardware-point/run-seed*")
    return runs


