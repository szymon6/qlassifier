def summary_values(v: Values, results: Mapping[str, Mapping[str, Any]]) -> None:
    """Numbers across datasets: ranges, means over the UCI sets, BT-3/BT-4 counts, noise extremes, protocol."""
    uci = [d for d in UCI if d in results]
    vszz = {ds: 100 * r["highlights"]["vs_standard_qml"]["mean_diff"] for ds, r in results.items()}
    v.add("uci.vszz.min", fixed(min(vszz[d] for d in uci), 1))
    v.add("uci.vszz.max", fixed(max(vszz[d] for d in uci), 1))
    v.add("all.vszz.min", fixed(min(vszz.values()), 1))
    v.add("all.vszz.max", fixed(max(vszz.values()), 1))
    best = [r["highlights"]["vs_best_classical"] for r in results.values()]
    v.add("all.vsbest.min", pp(min(b["mean_diff"] for b in best)))
    v.add("all.vsbest.max", pp(max(b["mean_diff"] for b in best)))
    half = [100 * (b["ci_high"] - b["ci_low"]) / 2 for b in best]
    v.add("all.halfwidth.min", fixed(min(half), 1))
