def _cell_ba(r: Mapping[str, Any], model_id: str) -> str:
    m = model(r, model_id)
    if m is None:
        return "---"
    s = m["metrics"]["balanced_accuracy"]
    top = max(x["metrics"]["balanced_accuracy"]["mean"] for x in r["models"])
    text = f"{fixed(s['mean'])} $\\pm$ {fixed(s['std'])}"
    if s["mean"] == top:
        text = rf"\textbf{{{text}}}"
    if s["tied_with_best"] and model_id != "trivial":
        text += r"$^{\approx}$"
    return text


