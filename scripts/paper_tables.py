def owned(paper: Path | None = None) -> list[Path]:
    """Files this script owns on disk (generated tables and copied figures)."""
    paper = paper or PAPER
    figures = paper / "figures"
    copied = [p for p in [*figures.glob("*.pdf"), *figures.glob("*.png")] if "-" in p.stem]  # <dataset>-<kind>
    return sorted([*(paper / "generated").glob("*.tex"), *copied])  # wins.pdf comes from scripts/wins_chart.py


def drift(files: Mapping[Path, bytes], paper: Path | None = None) -> list[str]:
    """Outputs that differ from disk: changed, missing, or stale extra files."""
    problems = []
    for path, data in files.items():
        if not path.is_file():
            problems.append(f"missing: {path}")
        elif path.read_bytes() != data:
            problems.append(f"differs: {path}")
    problems += [f"stale: {p}" for p in owned(paper) if p not in files]
    return problems


def write(files: Mapping[Path, bytes], paper: Path | None = None) -> None:
    """Write every output and remove stale generated files."""
    for p in owned(paper):
        if p not in files:
            p.unlink()
    for path, data in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_bytes() != data:
            path.write_bytes(data)


def main(argv: Sequence[str] | None = None) -> int:
    """Write the paper tables, or check that the committed ones match the saved results."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when a committed output is out of date")
    args = ap.parse_args(argv)
    try:
        files = build()
    except InputError as exc:
        print(f"paper_tables: {exc}", file=sys.stderr)
        return 2
    if args.check:
        problems = drift(files)
        for p in problems:
            print(f"paper_tables: {p}", file=sys.stderr)
        if problems:
            print("paper_tables: out of date; run python scripts/paper_tables.py", file=sys.stderr)
            return 1
        print(f"paper_tables: {len(files)} outputs match the saved results")
        return 0
    write(files)
    print(f"paper_tables: wrote {len(files)} outputs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
