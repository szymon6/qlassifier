def tex(text: str) -> str:
    """Escape plain text for LaTeX (pdfTeX-safe: non-ASCII symbols become math or text commands).

    Backtick spans become ``\\texttt``; ``>=`` / ``<=`` become relations; a hyphen before a digit becomes a minus.
    """
    parts = text.split("`")
    if len(parts) % 2 == 0:
        raise ValueError(f"unbalanced backticks in {text!r}")
    out = []
    for i, part in enumerate(parts):
        body = _tex_plain(part)
        out.append(rf"\texttt{{{body}}}" if i % 2 else body)
    return "".join(out)


def _tex_plain(text: str) -> str:
    text = text.replace(">=", "≥").replace("<=", "≤").replace(" - ", " − ")
    text = re.sub(r"(?<![\w)\]])-(?=\d)", "−", text)
    out = []
    for ch in text:
        if ch in SPECIAL_TEX:
            out.append(SPECIAL_TEX[ch])
        elif ch in UNICODE_TEX:
            out.append(UNICODE_TEX[ch])
        elif ord(ch) > 127:
            raise ValueError(f"no LaTeX mapping for {ch!r} in {text!r}")
        else:
            out.append(ch)
    return "".join(out)


def _minus(text: str, style: str) -> str:
    return text.replace("-", r"$-$" if style == "tex" else "−")


def fixed(x: float, nd: int = 3) -> str:
    """``0.948``; never a negative zero."""
    s = f"{x:.{nd}f}"
    return s[1:] if s.startswith("-") and float(s) == 0 else s


def signed(x: float, nd: int = 1, style: str = "tex") -> str:
    """``+37.6`` / ``−1.3`` (``0.0`` without a sign)."""
    s = fixed(x, nd)
    if float(s) == 0:
        return s
    return _minus(s if x < 0 else "+" + s, style)


def pp(diff: float, nd: int = 1, style: str = "tex") -> str:
    """A difference of fractions in percentage points, signed."""
    return signed(100 * diff, nd, style)


def ci_pp(lo: float | None, hi: float | None, nd: int = 1, style: str = "tex") -> str:
    """``[−3.1, +0.5]`` in percentage points."""
    if lo is None or hi is None:
        raise InputError("a confidence interval is missing (fewer than 2 seeds?)")
    return f"[{pp(lo, nd, style)}, {pp(hi, nd, style)}]"


def ci_abs(lo: float | None, hi: float | None, nd: int = 3) -> str:
    """``[0.928, 0.968]``."""
    if lo is None or hi is None:
        raise InputError("a confidence interval is missing (fewer than 2 seeds?)")
    return f"[{fixed(lo, nd)}, {fixed(hi, nd)}]"


def sci(x: float) -> str:
    """``$3.3\\times 10^{-16}$``."""
    mantissa, exponent = f"{x:.1e}".split("e")
    return rf"${mantissa}\times 10^{{{int(exponent)}}}$"


def thousands(n: float) -> str:
    """``2,423,299``."""
    return f"{round(n):,}"


def wins(win_rate: float, n: int) -> str:
    """Paired wins over seeds: ``10/10``."""
    return f"{round(win_rate * n)}/{n}"


# ----------------------------------------------------------------------------- inputs
def shown(path: Path) -> str:
    """A path for messages: relative to the repository when inside it."""
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


def read_json(path: Path) -> Any:
    """Parse one JSON input; a missing file names the command that writes it."""
    if not path.is_file():
        raise InputError(f"missing {shown(path)}: run `qlassifier benchmark --noise --out {shown(BENCH)}`")
    return json.loads(path.read_text(encoding="utf-8"))


def load_results(bench: Path, datasets: Sequence[str] = DATASETS) -> dict[str, dict[str, Any]]:
    """The complete protocol results (with noise and cost studies), by dataset id, in protocol order."""
    results = {}
    for ds in datasets:
        r = read_json(bench / ds / "result.json")
        if r.get("status") != "complete":
            raise InputError(f"{ds}/result.json has status {r.get('status')!r}, expected 'complete'")
        if r.get("noise") is None or r.get("cost") is None:
            raise InputError(f"{ds}/result.json has no noise or cost study: rerun with --noise")
        results[ds] = r
    return results


def read_rows(path: Path) -> list[dict[str, str]]:
    """Rows of a phase-7 CSV."""
    if not path.is_file():
        raise InputError(f"missing phase-7 file {shown(path)}")
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


@dataclass(frozen=True)
class Paired:
    """A phase-7 paired comparison (a - b) over seeds, as the phase-7 summaries computed it."""

    a: str
    b: str
    mean: float
    lo: float
    hi: float
    p: float
    win_rate: float
    n: int
    level: float


def phase7_paired(rows: Sequence[Mapping[str, str]], a: str, b: str, level: float = 0.95) -> Paired:
    """Corrected (Nadeau-Bengio) CI of the per-seed BA difference a - b; ratio = mean n_test / mean n_train of a."""
    from qlassifier.bench.stats import corrected_ci

    xa = {r["seed"]: r for r in rows if r["model"] == a}
    xb = {r["seed"]: r for r in rows if r["model"] == b}
    seeds = sorted(set(xa) & set(xb), key=int)
    if len(seeds) < 2:
        raise InputError(f"phase-7 rows hold fewer than 2 common seeds for {a} and {b}")
    d = [float(xa[s]["ba"]) - float(xb[s]["ba"]) for s in seeds]
    ratio = fmean(float(xa[s]["n_test"]) for s in seeds) / fmean(float(xa[s]["n_train"]) for s in seeds)
    m, lo, hi, p = corrected_ci(d, ratio, level)
    if lo is None or hi is None or p is None:
        raise InputError(f"no CI for {a} - {b}")
    return Paired(a, b, m, lo, hi, p, sum(x > 0 for x in d) / len(d), len(d), level)


def phase7_mean(rows: Sequence[Mapping[str, str]], model: str) -> float:
    """Mean BA of one model over the seeds of a phase-7 file."""
    vals = [float(r["ba"]) for r in rows if r["model"] == model]
    if not vals:
        raise InputError(f"no phase-7 rows for {model}")
    return fmean(vals)


def phase7_best_classical(rows: Sequence[Mapping[str, str]]) -> str:
    """Highest mean BA among the five classical models (ex post, as the protocol defines it)."""
    return max(PHASE7_CLASSICAL, key=lambda m: phase7_mean(rows, m))


def phase7_rows(experiments: Path, rel: str, dataset: str | None = None) -> list[dict[str, str]]:
    """Rows of one phase-7 file, optionally of one dataset only."""
    rows = read_rows(experiments / rel)
    return [r for r in rows if dataset is None or r["dataset"] == dataset]


