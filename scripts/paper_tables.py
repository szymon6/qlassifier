def final_gram_ratio(r: Mapping[str, Any]) -> float:
    """Circuits of the fidelity-kernel pipeline's final Gram matrices alone (no bandwidth search) / Qlassifier's."""
    final = float(cost_row(r, "fqk_bandwidth_linear")["circuits_fit_predict"])
    return final / float(cost_row(r, "qlassifier")["circuits_fit_predict"])


def edge_shares(results: Mapping[str, Mapping[str, Any]]) -> dict[str, tuple[float, list[str]]]:
    """Per tuned model: the highest share of seeds whose chosen config sits on a grid edge, and the datasets where."""
    out: dict[str, tuple[float, list[str]]] = {}
    for ds, r in results.items():
        for m in r["models"]:
            if r["protocol"]["configs_per_model"].get(m["id"], 0) <= 1:
                continue
            share = round(float(m["edge_share"]), 6)
            best, where = out.get(m["id"], (-1.0, []))
            if share > best:
                out[m["id"]] = (share, [ds])
            elif share == best:
                where.append(ds)
    return out


def edge_values(v: Values, results: Mapping[str, Mapping[str, Any]]) -> None:
    """Grid-edge shares: the models that sit on an edge on at least half the seeds somewhere, and Qlassifier's own."""
    shares = edge_shares(results)
    names = {m["id"]: m["name"] for r in results.values() for m in r["models"]}
    order = {mid: i for i, mid in enumerate(ROWS)}
    frequent = sorted(
        (mid for mid, (share, _) in shares.items() if share >= 0.5), key=lambda m: (-shares[m][0], order[m])
    )
    v.add(
        "edge.list",
        "; ".join(
            f"{tex(names[mid])} {fixed(shares[mid][0], 1)} ({', '.join(LABEL[d] for d in shares[mid][1])})"
            for mid in frequent
        ),
    )
    share, where = shares["qlassifier"]
    v.add("edge.qlassifier.max", fixed(share, 1))
    v.add("edge.qlassifier.where", ", ".join(LABEL[d] for d in where))


def rank_text(r: Mapping[str, Any], model_id: str) -> str:
    """``1st of 13`` by mean BA (the benchmark's own rank)."""
    m = model(r, model_id)
    if m is None:
        raise InputError(f"no model {model_id}")
    k = int(m["rank"])
    suffix = "th" if 10 <= k % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(k % 10, "th")
    return f"{k}{suffix} of {len(r['models'])}"


VERDICT_WORD = {
    "tie": "a statistical tie (the CI contains 0)",
    "win": "a significant win (the CI lies above 0)",
    "loss": "a significant loss (the CI lies below 0)",
}


def verdict(d: Mapping[str, Any]) -> str:
    """``tie`` / ``win`` / ``loss`` from the corrected CI of a paired difference."""
    if d["ci_low"] is None or d["ci_high"] is None:
        raise InputError("a paired difference has no CI")
    if d["ci_low"] > 0:
        return "win"
    if d["ci_high"] < 0:
        return "loss"
    return "tie"


def per_seed(r: Mapping[str, Any], model_id: str, name: str = "balanced_accuracy") -> dict[int, float]:
    """Per-seed values of one model."""
    return {int(x["seed"]): float(x[name]) for x in r["runs"] if x["model"] == model_id}


def twin_words(r: Mapping[str, Any]) -> str:
    """How geometry mode and its classical twin compare, seed by seed (the Gram identity predicts: identical)."""
    q, t = per_seed(r, "qlassifier"), per_seed(r, "classical_twin")
    seeds = sorted(set(q) & set(t))
    if not seeds:
        raise InputError("no seeds with both geometry mode and the classical twin")
    gap = max(abs(q[s] - t[s]) for s in seeds)
    if gap < 1e-12:
        return f"identical on all {len(seeds)} seeds, as the Gram identity requires"
    return f"a largest per-seed difference of {fixed(100 * gap, 2)} pp"


