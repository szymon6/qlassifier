# ----------------------------------------------------------------------------- claims
def claims(results: Mapping[str, Mapping[str, Any]]) -> list[str]:
    """The qualitative sentences of ``main.tex`` and the README, checked against the results.

    Returns the claims that no longer hold; ``build`` refuses to write while any fails, so the text must be fixed.
    """
    failed: list[str] = []

    def claim(ok: bool, text: str) -> None:
        if not ok:
            failed.append(text)

    for ds, r in results.items():
        z = r["highlights"]["vs_standard_qml"]
        claim(z["win_rate"] == 1.0 and verdict(z) == "win", f"{ds}: Qlassifier beats ZZ QSVC on every seed, CI > 0")
        claim(verdict(r["highlights"]["vs_best_classical"]) == "tie", f"{ds}: tied with the best classical model")
        claim(max(cost_row(r, "qlassifier")["two_qubit_gates"].values()) == 0, f"{ds}: no two-qubit gates")
    uci = [d for d in UCI if d in results]
    means = {m: fmean(metric(results[d], m)["mean"] for d in uci) for m in QUANTUM}
    claim(max(means, key=means.__getitem__) == "qlassifier", "top mean BA of the in-harness quantum models (UCI)")
    bc = results.get("breast_cancer")
    if bc is not None:
        claim(bool(metric(bc, "qlassifier")["tied_with_best"]), "Breast Cancer: Qlassifier inside the tie band")
        ns = noise_summary(bc)
        claim(
            all(ns[("B", "qlassifier", d)]["drop_mean_pp"] < ns[("B", "fqk_bandwidth_linear", d)]["drop_mean_pp"]
                for d in DEVICES),
            "part B: Qlassifier loses less than FQK-bw linear on every device",
        )  # fmt: skip
        q, pq, fq = cost_row(bc, "qlassifier"), cost_row(bc, "pqk"), cost_row(bc, "fqk_bandwidth_linear")
        claim(
            pq["circuits_fit_predict"] == q["circuits_fit_predict"] and min(pq["two_qubit_gates"].values()) > 0,
            "PQK needs as many circuits as Qlassifier, plus two-qubit gates",
        )
        claim(
            fq["tuning_circuits_on_device"] > fq["circuits_fit_predict"],
            "the FQK-bw pipeline spends most circuits on its bandwidth search",
        )
    return failed


