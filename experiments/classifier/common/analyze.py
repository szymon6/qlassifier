"""Summarise a results CSV under the protocol statistics (../README.md §2.7).

Usage:
  .venv/bin/python analyze.py RESULTS.csv [RESULTS2.csv ...] [--cands a b] [--ref bloch_gauss] [--out summary.md]
Prints (and optionally writes) mean ± std BA per dataset, Δ vs best classical with the corrected resampled t-test
(Nadeau & Bengio 2003), and Δ vs a reference model. Up: ../README.md · Log: ../learning-log.md
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lab  # noqa: E402

CLASSICAL = ["logreg", "rbf_svm", "random_forest", "grad_boost", "mlp"]


def table(df: pd.DataFrame, metric: str = "ba") -> pd.DataFrame:
    g = df.groupby(["model", "dataset"])[metric]
    t = (g.mean().unstack().round(3).astype(str) + " ± " + g.std().unstack().round(3).astype(str))
    t["mean"] = df.groupby(["model", "dataset"])[metric].mean().unstack().mean(axis=1).round(3)
    return t.sort_values("mean", ascending=False)


def paired(df: pd.DataFrame, a: str, b: str, ds: str, metric: str = "ba"):
    x = df[(df.dataset == ds) & (df.model == a)].set_index("seed")[metric]
    y = df[(df.dataset == ds) & (df.model == b)].set_index("seed")[metric]
    idx = x.index.intersection(y.index)
    if len(idx) < 2:
        return None
    d = (x.loc[idx] - y.loc[idx]).to_numpy()
    r = df[(df.dataset == ds) & (df.model == a)].set_index("seed").loc[idx]  # grouped splits: sizes vary by seed
    m, lo, hi, p = lab.corrected_ci(d, float(r.n_train.mean()), float(r.n_test.mean()))
    return m, lo, hi, p, float((d > 0).mean()), len(idx)


def best_classical(df: pd.DataFrame, ds: str, classical=CLASSICAL, metric: str = "ba") -> str | None:
    sub = df[(df.dataset == ds) & (df.model.isin(classical))]
    if sub.empty:
        return None
    return sub.groupby("model")[metric].mean().idxmax()


def report(df: pd.DataFrame, cands: list[str], ref: str | None, classical=CLASSICAL) -> str:
    lines = ["## Balanced accuracy, mean ± std over seeds", "", table(df).to_markdown(), ""]
    lines += ["## Δ vs best classical (corrected resampled t, 95% CI, pp; win rate = share of splits Q > classical)", "",
              "| candidate | dataset | best classical | Δ [95% CI] | p | wins |", "|---|---|---|---|---|---|"]
    for ds in sorted(df.dataset.unique()):
        bc = best_classical(df, ds, classical)
        if bc is None:
            continue
        bcm = df[(df.dataset == ds) & (df.model == bc)].ba.mean()
        for c in cands:
            r = paired(df, c, bc, ds)
            if r is None:
                continue
            m, lo, hi, p, w, J = r
            lines.append(f"| {c} | {ds} | {bc} {bcm:.3f} | {100*m:+.1f} [{100*lo:+.1f}, {100*hi:+.1f}] | {p:.3f} | {w:.0%} of {J} |")
    if ref:
        lines += ["", f"## Δ vs {ref} (pp, corrected CI)", "", "| candidate | dataset | Δ [95% CI] | wins |", "|---|---|---|---|"]
        for ds in sorted(df.dataset.unique()):
            for c in cands:
                if c == ref:
                    continue
                r = paired(df, c, ref, ds)
                if r is None:
                    continue
                m, lo, hi, p, w, J = r
                lines.append(f"| {c} | {ds} | {100*m:+.1f} [{100*lo:+.1f}, {100*hi:+.1f}] | {w:.0%} of {J} |")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("csv", nargs="+")
    ap.add_argument("--cands", nargs="*", default=None)
    ap.add_argument("--ref", default=None)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    df = pd.concat([pd.read_csv(f) for f in a.csv], ignore_index=True)
    cands = a.cands or [m for m in df.model.unique() if m not in CLASSICAL and m != "trivial"]
    txt = report(df, cands, a.ref)
    print(txt)
    if a.out:
        Path(a.out).write_text(f"# Summary (generated by common/analyze.py)\n\nSources: {', '.join(Path(f).name for f in a.csv)}\n\n" + txt + "\n")


if __name__ == "__main__":
    main()
