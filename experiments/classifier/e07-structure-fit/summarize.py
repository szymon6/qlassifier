"""e07 summary: BT-6 (geometry mode vs every tuned classical model), BT-2 (vs pinned ZZ), H8 ablation (geometry off).

Up: README.md · Stats: ../common/lab.py (corrected_ci) · Writes summary.md next to this file.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
import analyze  # noqa: E402
import lab  # noqa: E402

CL = analyze.CLASSICAL
files = [f for f in ("quakes.csv", "protein.csv") if (HERE / f).exists()]
df = pd.concat([pd.read_csv(HERE / f) for f in files], ignore_index=True).drop_duplicates(["dataset", "seed", "model"])
out = [f"# e07 summary (generated by summarize.py)\n\nSources: {', '.join(files)}\n"]
for ds in sorted(df.dataset.unique()):
    sub = df[df.dataset == ds]
    J = sub.seed.nunique()
    g = sub.groupby("model")
    t = pd.DataFrame({"BA": g.ba.mean(), "BA sd": g.ba.std(), "acc": g.acc.mean(), "AUC": g.auc.mean(), "F1": g.f1.mean(),
                      "tune s": g.t_tune.mean()}).sort_values("BA", ascending=False).round(3)
    out += [f"## {ds} ({J} fresh seeds, n_train {int(sub.n_train.iloc[0])}, n_test {int(sub.n_test.iloc[0])})", "", t.to_markdown(), ""]
    best = sub[sub.model.isin(CL)].groupby("model").ba.mean().idxmax()
    rows = ["| comparison | Δ BA pp [corrected 95% CI] | p | wins |", "|---|---|---|---|"]
    for a, b in [("qlass_geo", best)] + [("qlass_geo", c) for c in CL if c != best] + [("qlass_geo", "zz_qsvc"), ("qlass_geo", "bloch_gauss"),
                                                                                  ("qlass_geo", "separable"), ("bloch_gauss", best)]:
        r = analyze.paired(sub, a, b, ds)
        if r is None:
            continue
        m, lo, hi, p, w, n = r
        rows.append(f"| {a} − {b} | {100*m:+.1f} [{100*lo:+.1f}, {100*hi:+.1f}] | {p:.3f} | {w:.0%} of {n} |")
    q = sub[sub.model == "qlass_geo"].ba.mean()
    above_all = all(q > sub[sub.model == c].ba.mean() for c in CL)
    r = analyze.paired(sub, "qlass_geo", best, ds)
    verdict = "MET" if (above_all and r and r[1] > 0) else ("mean above every classical, CI spans 0" if above_all else "not above every classical")
    note = (" on residue-level splits (superseded by e11: chain-grouped splits, BT-6 missed)" if ds == "protein_strands" else "")
    out += [f"Best classical: {best}. BT-6 on {ds}: **{verdict}**{note}.", ""] + rows + [""]
txt = "\n".join(out)
(HERE / "summary.md").write_text(txt)
print(txt)
