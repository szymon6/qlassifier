"""e11 summary: chain-grouped splits on protein_strands (H11). Compares with the residue-level splits of e07.

Up: README.md · Stats: ../common/analyze.py (paired; corrected CI with mean realised n_te/n_tr) · Writes summary.md.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
import analyze  # noqa: E402

CL = analyze.CLASSICAL
g = pd.read_csv(HERE / "results.csv")
r = pd.read_csv(HERE.parent / "e07-structure-fit" / "protein.csv")
ds = "protein_strands"
out = ["# e11 summary (generated by summarize.py)", "",
       f"Grouped splits: n_train {int(g.n_train.min())}–{int(g.n_train.max())}, n_test {int(g.n_test.min())}–{int(g.n_test.max())}; "
       f"mean n_te/n_tr {(g.n_test / g.n_train).mean():.3f}.", ""]
tab = pd.DataFrame({
    "BA grouped": g.groupby("model").ba.mean(), "BA sd": g.groupby("model").ba.std(),
    "acc": g.groupby("model").acc.mean(), "AUC": g.groupby("model").auc.mean(), "F1": g.groupby("model").f1.mean(),
    "BA residue split (e07)": r.groupby("model").ba.mean()}).sort_values("BA grouped", ascending=False).round(3)
out += [tab.to_markdown(), ""]
best = g[g.model.isin(CL)].groupby("model").ba.mean().idxmax()
out += [f"Best classical (grouped): {best}.", "", "| comparison | metric | Δ pp [corrected 95% CI] | p | wins |", "|---|---|---|---|---|"]
pairs = [("qlass_geo", best)] + [("qlass_geo", c) for c in CL if c != best] + [("qlass_geo", "zz_qsvc"), ("qlass_geo", "bloch_gauss"), ("qlass_geo", "separable")]
for a, b in pairs:
    for met in (["ba", "acc", "auc", "f1"] if b == best else ["ba"]):
        res = analyze.paired(g, a, b, ds, metric=met)
        if res is None:
            continue
        m, lo, hi, p, w, n = res
        out.append(f"| {a} − {b} | {met} | {100*m:+.1f} [{100*lo:+.1f}, {100*hi:+.1f}] | {p:.3f} | {w:.0%} of {n} |")
q = g[g.model == "qlass_geo"].ba.mean()
above = all(q > g[g.model == c].ba.mean() for c in CL)
res = analyze.paired(g, "qlass_geo", best, ds)
verdict = "MET" if (above and res[1] > 0) else ("mean above every classical, CI spans 0" if above else "not above every classical")
out += ["", f"BT-6 under chain-grouped splits: **{verdict}**."]
txt = "\n".join(out)
(HERE / "summary.md").write_text(txt + "\n")
print(txt)
