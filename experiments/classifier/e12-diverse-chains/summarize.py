"""e12 summary: pre-registered analysis of H12 (`protein_div6`) and H13 (`protein_div10`), learning log iteration 5.

Pass = geometry mean BA above all five classical models AND corrected (Nadeau-Bengio) 97.5% CI of Delta vs the best
classical > 0 (Bonferroni, k = 2). Mean realised n_te/n_tr. Writes summary.md. Up: README.md
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
import lab  # noqa: E402

CL = ["logreg", "rbf_svm", "random_forest", "grad_boost", "mlp"]
LEVEL = 0.975


def paired(df, a, b, metric="ba"):
    x = df[df.model == a].set_index("seed")[metric]
    y = df[df.model == b].set_index("seed")[metric]
    idx = x.index.intersection(y.index)
    d = (x.loc[idx] - y.loc[idx]).to_numpy()
    r = df[df.model == a].set_index("seed").loc[idx]
    m, lo, hi, p = lab.corrected_ci(d, float(r.n_train.mean()), float(r.n_test.mean()), level=LEVEL)
    return m, lo, hi, p, float((d > 0).mean()), len(idx)


out = ["# e12 summary (generated by summarize.py)", "", f"Corrected CIs at {LEVEL:.1%} (Bonferroni, k = 2).", ""]
for f, hyp in (("div6.csv", "H12"), ("div10.csv", "H13")):
    if not (HERE / f).exists():
        continue
    df = pd.read_csv(HERE / f)
    ds = df.dataset.iloc[0]
    g = df.groupby("model")
    tab = pd.DataFrame({"BA": g.ba.mean(), "BA sd": g.ba.std(), "acc": g.acc.mean(), "AUC": g.auc.mean(), "F1": g.f1.mean(),
                        "tune s": g.t_tune.mean()}).sort_values("BA", ascending=False).round(3)
    best = df[df.model.isin(CL)].groupby("model").ba.mean().idxmax()
    out += [f"## {hyp}: {ds} ({df.seed.nunique()} fresh seeds, n_train {int(df.n_train.min())}–{int(df.n_train.max())}, "
            f"n_test {int(df.n_test.min())}–{int(df.n_test.max())}, mean n_te/n_tr {(df.n_test / df.n_train).mean():.3f})", "",
            tab.to_markdown(), "", f"Best classical: {best}.", "",
            "| comparison | metric | Δ pp [corrected 97.5% CI] | p | wins |", "|---|---|---|---|---|"]
    for b in [best] + [c for c in CL if c != best] + ["zz_qsvc", "bloch_gauss", "separable"]:
        for met in (["ba", "acc", "auc", "f1"] if b == best else ["ba"]):
            m, lo, hi, p, w, n = paired(df, "qlass_geo", b, met)
            out.append(f"| qlass_geo − {b} | {met} | {100*m:+.2f} [{100*lo:+.2f}, {100*hi:+.2f}] | {p:.4f} | {w:.0%} of {n} |")
    q = df[df.model == "qlass_geo"].ba.mean()
    above = all(q > df[df.model == c].ba.mean() for c in CL)
    lo = paired(df, "qlass_geo", best)[1]
    verdict = "PASS" if (above and lo > 0) else ("FAIL (mean above every classical, CI includes 0)" if above else "FAIL (mean not above every classical)")
    out += ["", f"**{hyp} verdict (pre-registered rule): {verdict}.**", ""]
txt = "\n".join(out)
(HERE / "summary.md").write_text(txt + "\n")
print(txt)
