"""e02 aggregation: accuracy-vs-noise-scale tables, AUC per model, BT-2 verdict, plot.

Up: README.md · Protocol: ../README.md §2.3 · Input: cells.jsonl (noise_sweep.py) · Output: summary.md, cells.csv, accuracy_vs_noise.png
Run: .venv/bin/python experiments/hardware/e02-noise-sweep/analyze.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
rows = [json.loads(l) for l in (HERE / "cells.jsonl").read_text().splitlines()]
df = pd.DataFrame(rows)
df.to_csv(HERE / "cells.csv", index=False)
NAMES = {"qlassifier": "Qlassifier", "fqk_bandwidth_linear": "FQK-bw linear", "zz_qsvc": "ZZ QSVC"}


def auc(g: pd.DataFrame, metric: str) -> float:
    """Trapezoid over the measured scales divided by the span (sweep-mean accuracy; range 0-1)."""
    m = g.groupby("scale")[metric].mean().sort_index()
    return float(np.trapezoid(m.to_numpy(), m.index.to_numpy()) / (m.index.max() - m.index.min()))


lines = ["# e02 summary — accuracy vs noise scale (FakeFez × s), Breast Cancer", "",
         "Generated by analyze.py from cells.jsonl. Drop = exact − noisy, pp (mean over seeds / worst seed). r = kernel Pearson r vs exact (training block).", ""]
for part in ("A", "B"):
    sub = df[df.part == part]
    if sub.empty:
        continue
    seeds = sorted(int(x) for x in sub.seed.unique())
    lines += [f"## Part {part} ({'all 569 rows, seeds ' + str(seeds) if part == 'A' else 'paired 60 train / 40 test subset, seeds ' + str(seeds)})", "",
              "| Model | s | n seeds | Acc | BA | Drop acc (mean / worst) | Drop BA (mean) | r | Circuits | 2Q gates | Depth |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for model in ("qlassifier", "fqk_bandwidth_linear", "zz_qsvc"):
        g = sub[sub.model == model]
        if g.empty:
            continue
        ex = g.drop_duplicates("seed")
        lines.append(f"| {NAMES[model]} | exact | {len(ex)} | {ex.exact_accuracy.mean():.3f} | {ex.exact_balanced_accuracy.mean():.3f} | — | — | 1.000 | — | — | — |")
        for s, gs in g.groupby("scale"):
            lines.append(f"| {NAMES[model]} | {s:g} | {len(gs)} | {gs.accuracy.mean():.3f} | {gs.balanced_accuracy.mean():.3f} | {gs.drop_pp.mean():+.2f} / {gs.drop_pp.max():+.2f} | {gs.drop_ba_pp.mean():+.2f} | {gs.kernel_r.mean():.4f} | {int(gs.circuits.iloc[0]):,} | {int(gs.two_qubit_gates.iloc[0])} | {int(gs.depth.iloc[0])} |")
    lines.append("")
    lines += ["| Model | scales measured | AUC accuracy (sweep mean) | AUC BA |", "|---|---|---|---|"]
    aucs = {}
    for model in ("qlassifier", "fqk_bandwidth_linear", "zz_qsvc"):
        g = sub[sub.model == model]
        if g.empty:
            continue
        aucs[model] = (auc(g, "accuracy"), auc(g, "balanced_accuracy"))
        lines.append(f"| {NAMES[model]} | {[float(x) for x in sorted(g.scale.unique())]} | {aucs[model][0]:.4f} | {aucs[model][1]:.4f} |")
    lines.append("")
    if part == "A":
        q1 = sub[(sub.model == "qlassifier") & (sub.scale == 1.0)]
        q3 = sub[(sub.model == "qlassifier") & (sub.scale == 3.0)]
        lines.append(f"- BT-2 (i) part-A mean accuracy drop at s = 1: **{q1.drop_pp.mean():+.2f} pp** (worst seed {q1.drop_pp.max():+.2f}); at s = 3: {q3.drop_pp.mean():+.2f} pp (worst {q3.drop_pp.max():+.2f}). Rule ≤ 2 pp at s = 1 → **{'met' if q1.drop_pp.mean() <= 2 else 'missed'}**.")
    else:
        q, f, z = aucs.get("qlassifier"), aucs.get("fqk_bandwidth_linear"), aucs.get("zz_qsvc")
        if q and f and z:
            ok = q[0] > f[0] and q[0] > z[0]
            lines.append(f"- BT-2 (ii) part-B AUC accuracy: Qlassifier {q[0]:.4f} vs FQK-bw linear {f[0]:.4f} vs ZZ QSVC {z[0]:.4f} → **{'met' if ok else 'missed'}** (BA: {q[1]:.4f} / {f[1]:.4f} / {z[1]:.4f}).")
    lines.append("")
(HERE / "summary.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))

try:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8), sharey=False)
    for ax, part, title in zip(axes, ("A", "B"), ("Part A: all rows, Qlassifier", "Part B: paired 60/40 subset"), strict=True):
        sub = df[df.part == part]
        for model, color in (("qlassifier", "#1b6ca8"), ("fqk_bandwidth_linear", "#d1495b"), ("zz_qsvc", "#8a8a8a")):
            g = sub[sub.model == model]
            if g.empty:
                continue
            m = g.groupby("scale").accuracy.agg(["mean", "std"]).sort_index()
            ax.errorbar(m.index, m["mean"], yerr=m["std"].fillna(0), marker="o", color=color, label=NAMES[model], capsize=3)
            ex = g.drop_duplicates("seed").exact_accuracy.mean()
            ax.axhline(ex, color=color, ls=":", lw=1)
        ax.axhline(0.626, color="black", ls="--", lw=0.8, label="majority class")
        ax.set_xlabel("noise scale s (× FakeFez error rates)")
        ax.set_ylabel("test accuracy")
        ax.set_title(title)
        ax.set_ylim(0.5, 1.0)
        ax.grid(alpha=0.3)
    axes[1].legend(loc="lower left", fontsize=8)
    fig.tight_layout()
    fig.savefig(HERE / "accuracy_vs_noise.png", dpi=150)
    print("plot written")
except Exception as e:  # noqa: BLE001
    print("plot skipped:", e)
